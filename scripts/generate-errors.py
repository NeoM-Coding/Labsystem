#!/usr/bin/env python3
"""Generate shared contracts. Run with --check in CI to detect drift."""
import json, sys, re
from pathlib import Path
root = Path(__file__).resolve().parents[1]
entries = json.loads((root / 'contracts/errors.json').read_text())
assert len({e['code'] for e in entries}) == len(entries), 'Duplicate business code'
assert len({e['name'] for e in entries}) == len(entries), 'Duplicate error name'
assert all(100000 <= e['code'] <= 179999 for e in entries)
java = '''// Generated by scripts/generate-errors.py; edit contracts/errors.json instead.
package xyz.jasenon.lab.common.error;

import xyz.jasenon.lab.common.rpc.RpcErrorType;

public enum ErrorCode {
'''
java += ',\n'.join('    %s(%d, %d, %s, RpcErrorType.%s)' % (e['name'], e['code'], e['httpStatus'], json.dumps(e['message'],ensure_ascii=False), e['type']) for e in entries) + ';\n'
java += '''
    private final int code;
    private final int httpStatus;
    private final String message;
    private final RpcErrorType type;
    ErrorCode(int code, int httpStatus, String message, RpcErrorType type) {
        this.code = code; this.httpStatus = httpStatus; this.message = message; this.type = type;
    }
    public int code() { return code; }
    public int httpStatus() { return httpStatus; }
    public String message() { return message; }
    public RpcErrorType type() { return type; }
    public static ErrorCode fromCode(int code) {
        for (ErrorCode value : values()) if (value.code == code) return value;
        throw new IllegalArgumentException("Unknown business code: " + code);
    }
    public static ErrorCode forHttpStatus(int status) {
        return switch (status) {
            case 400 -> VALIDATION_FAILED;
            case 401 -> AUTHENTICATION_REQUIRED;
            case 403 -> PERMISSION_DENIED;
            case 404 -> RESOURCE_NOT_FOUND;
            case 409 -> BUSINESS_CONFLICT;
            case 422 -> BUSINESS_FAILED;
            case 502 -> INVALID_RPC_RESPONSE;
            case 503 -> DEPENDENCY_UNAVAILABLE;
            case 504 -> RPC_TIMEOUT;
            default -> INTERNAL_ERROR;
        };
    }
}
'''
ts = '// Generated from lab-system-cloud/contracts/errors.json.\nexport const errorCatalog = '+json.dumps({str(e['code']):e for e in entries},ensure_ascii=False,indent=2)+' as const\n\nexport const ErrorCode = '+json.dumps({e['name']:e['code'] for e in entries},indent=2)+' as const\n'
files={root/'shared/common/src/main/java/xyz/jasenon/lab/common/error/ErrorCode.java':java,root.parent/'lab-system-frontend/src/shared/api/errorCodes.ts':ts}
for path, content in files.items():
    if '--check' in sys.argv:
        if path.suffix == '.ts' and not path.parent.exists():
            continue  # Backend-only checkout; the combined workspace also checks TypeScript.
        assert path.exists() and path.read_text()==content, f'Generated contract out of date: {path}'
    else:
        path.parent.mkdir(parents=True,exist_ok=True); path.write_text(content)
if '--check' in sys.argv:
    for path in root.rglob('*.java'):
        if '/src/main/' not in str(path): continue
        assert not re.search(r'new BusinessException\((?:\d{3}|BAD_REQUEST|NOT_FOUND|FORBIDDEN|UNAUTHORIZED|CONFLICT|INTERNAL_SERVER_ERROR),',path.read_text()), f'Bare HTTP business code: {path}'
        assert not re.search(r'R\.fail\(\s*\d{3}\s*,\s*(?:\d{3}|"|BAD_REQUEST|NOT_FOUND)',path.read_text()), f'Bare HTTP response business code: {path}'
# Ensure every production enum reference resolves, including after catalog renames.
known = {e['name'] for e in entries}
for path in root.rglob('*.java'):
    if '/src/main/' not in str(path) or path.name == 'ErrorCode.java': continue
    for name in re.findall(r'ErrorCode\.([A-Z][A-Z_0-9]+)', path.read_text()):
        assert name in known, f'Unknown error {name}: {path}'
print(f'{len(entries)} error definitions verified')
